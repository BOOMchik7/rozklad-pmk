let currentGroup = "ПМК-21";

let currentDay = "Понеділок";


const groupSelect =
    document.getElementById("groupSelect");

const dayNav =
    document.getElementById("dayNav");

const schedule =
    document.getElementById("schedule");



/* ==========================================
   ДНІ
========================================== */

function renderDays() {

    dayNav.innerHTML = "";

    days.forEach(function(day) {

        const button =
            document.createElement("button");

        button.className = "day-btn";

        if (day === currentDay) {
            button.classList.add("active");
        }

        button.textContent = day;


        button.addEventListener(
            "click",
            function() {

                currentDay = day;

                renderDays();

                renderSchedule();

            }
        );


        dayNav.appendChild(button);

    });

}



/* ==========================================
   HTML ПРЕДМЕТА
========================================== */

function lessonHTML(item) {

    let html = "";

    html += `
        <div class="subject">
            ${item.subject}
        </div>
    `;


    if (item.type) {

        html += `
            <span class="type">
                ${item.type}
            </span>
        `;

    }


    if (item.room) {

        html += `
            <span class="room">
                ауд. ${item.room}
            </span>
        `;

    }


    if (item.teachers) {

        html += `
            <div class="teachers">
                ${item.teachers}
            </div>
        `;

    }


    return html;

}



/* ==========================================
   ВМІСТ ПАРИ
========================================== */

function createLessonContent(item) {


    /* Порожня пара */

    if (item === null) {

        return `
            <div class="lesson-content">
                <span>Занять немає</span>
            </div>
        `;

    }


    /* Два предмети в одній комірці */

    if (item.multiple) {

        return `

            <div class="lesson-content split">

                <div class="branch">

                    <div class="branch-title">
                        Запис 1
                    </div>

                    ${lessonHTML(item.first)}

                </div>


                <div class="branch">

                    <div class="branch-title">
                        Запис 2
                    </div>

                    ${lessonHTML(item.second)}

                </div>

            </div>

        `;

    }


    /* Звичайна пара */

    return `

        <div class="lesson-content">

            ${lessonHTML(item)}

        </div>

    `;

}



/* ==========================================
   ВИВЕДЕННЯ РОЗКЛАДУ
========================================== */

function renderSchedule() {

    schedule.innerHTML = "";


    const lessons =
        schedules[currentGroup][currentDay];


    /*
       ЗАВЖДИ ВИВОДИМО 5 ПАР.

       Не робимо filter().
       Не видаляємо null.
       Тому номер пари завжди правильний.
    */

    for (let i = 0; i < 5; i++) {

        const item = lessons[i];


        const card =
            document.createElement("article");


        if (item === null) {

            card.className =
                "lesson empty";

        } else {

            card.className =
                "lesson";

        }


        card.innerHTML = `

            <div class="pair-info">

                <div class="pair-number">
                    ${pairNames[i]} пара
                </div>

                <div class="time">
                    ${times[i]}
                </div>

            </div>


            ${createLessonContent(item)}

        `;


        schedule.appendChild(card);

    }

}



